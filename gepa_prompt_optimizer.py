#!/usr/bin/env python3
"""Optimize the FPGA routing decision prompt with GEPA through OpenRouter.

The script:
- loads GEPA JSONL examples generated by gepa_dataset_builder.py
- samples a configured percentage of examples deterministically
- asks the OpenRouter task model to predict the winning strategy
- optimizes the prompt with GEPA using an OpenRouter reflection model
- writes the best prompt and optimization metadata locally
"""

from __future__ import annotations

import json
import random
from pathlib import Path
from typing import Any, Dict, Iterable, List, Mapping, Sequence

import gepa
import litellm
from gepa.core.adapter import EvaluationBatch


CONFIG_PATH = Path("gepa_config.json")

BEGINNING_PROMPT = r"""You are the decision-maker in an FPGA timing-optimization pipeline for AMD UltraScale+ (xcvu3p). A fully placed and routed checkpoint is open in Vivado. Your goal: maximize Fmax within a hard wall-clock budget. Execution, validation, checkpoint banking, and reverts are handled by the harness — you only pick the next action and its parameters.

AVAILABLE ACTIONS:
{    "vv-place-explore",
    "vv-place-aggexp",
    "vv-route-explore",
    "vv-route-aggexp",
    "vv-physopt-explore",
    "vv-physopt-aggexp",
    "vv-physopt-altretime",
    "suggest-pblock"}

PLAYBOOK (empirical):
Every banked improvement is safe. Failed/regressed actions are auto-reverted — the cost is only the wasted runtime. Be aggressive early, conservative near the deadline.

physopt is a polish (typically <2% when WNS < -0.5ns). Run it after a successful placement/routing change, not as the main act.

On large designs, reroute with AggressiveExplore is the lever (+24-31% observed). suggest_pb is the only affordable placement fix there.

Given the checkpoint state below, return exactly one action name from AVAILABLE ACTIONS and nothing else.

CHECKPOINT STATE:
{state}"""

ACTIONS = {
    "vv-place-explore",
    "vv-place-aggexp",
    "vv-route-explore",
    "vv-route-aggexp",
    "vv-physopt-explore",
    "vv-physopt-aggexp",
    "vv-physopt-altretime",
    "suggest-pblock",
}


class OpenRouterLM:
    def __init__(
        self,
        api_key: str,
        model: str,
        temperature: float,
        max_tokens: int,
        timeout_seconds: float,
    ) -> None:
        self.api_key = api_key
        self.model = model
        self.temperature = temperature
        self.max_tokens = max_tokens
        self.timeout_seconds = timeout_seconds

    def __call__(self, prompt: str, **kwargs: Any) -> str:
        try:
            response = litellm.completion(
                model=self.model,
                api_key=self.api_key,
                messages=[{"role": "user", "content": prompt}],
                temperature=kwargs.get("temperature", self.temperature),
                max_tokens=kwargs.get("max_tokens", self.max_tokens),
                timeout=self.timeout_seconds,
            )
            return (response.choices[0].message.content or "").strip()
        except Exception as exc:
            return f"Error: OpenRouter request failed: {exc}"


class FPGARoutingAdapter:
    def __init__(
        self,
        task_lm: OpenRouterLM,
        seed: int,
    ) -> None:
        self.task_lm = task_lm
        self.seed = seed

    @staticmethod
    def format_state(example: Mapping[str, Any]) -> str:
        keys = (
            "worst_negative_slack",
            "clock_period",
            "avg_critical_path_distance_tiles",
            "max_critical_path_distance_tiles",
            "paths_analyzed",
            "num_high_fanout_nets",
            "levels_left_until_final_level",
            "benchmark",
            "mining_level",
            "notes",
        )
        lines = []
        for key in keys:
            value = example.get(key)
            if value is not None:
                lines.append(f"{key}: {value}")
        return "\n".join(lines)

    @staticmethod
    def parse_action(text: str) -> str:
        cleaned = text.strip().strip("`\n\r \t")
        if cleaned in ACTIONS:
            return cleaned

        for action in ACTIONS:
            if action in cleaned:
                return action
        return "<invalid_action>"

    def evaluate(
        self,
        batch: List[Mapping[str, Any]],
        candidate: Dict[str, str],
        capture_traces: bool = False,
    ) -> EvaluationBatch:
        prompt_template = candidate["routing_prompt"]
        outputs: List[Dict[str, Any]] = []
        scores: List[float] = []
        trajectories: List[Dict[str, Any]] | None = [] if capture_traces else None

        for example in batch:
            state = self.format_state(example)
            prompt = prompt_template.replace("{state}", state)
            raw_output = self.task_lm(prompt)
            predicted = self.parse_action(raw_output)

            expected = str(example.get("best_wns_strategy_by_final_level") or "").strip()
            if predicted in ACTIONS and predicted == expected:
                score = 1.0
            elif predicted in ACTIONS:
                score = 0.0
            else:
                score = 0.0

            output = {
                "predicted_action": predicted,
                "raw_output": raw_output,
                "expected_action": expected,
            }
            outputs.append(output)
            scores.append(score)

            if trajectories is not None:
                trajectories.append(
                    {
                        "state": state,
                        "predicted_action": predicted,
                        "raw_output": raw_output,
                        "expected_action": expected,
                        "score": score,
                        "benchmark": example.get("benchmark"),
                        "mining_level": example.get("mining_level"),
                    }
                )

        return EvaluationBatch(outputs=outputs, scores=scores, trajectories=trajectories)

    def make_reflective_dataset(
        self,
        candidate: Dict[str, str],
        eval_batch: EvaluationBatch,
        components_to_update: List[str],
    ) -> Mapping[str, Sequence[Mapping[str, Any]]]:
        reflective: Dict[str, Sequence[Mapping[str, Any]]] = {}

        if "routing_prompt" not in components_to_update:
            return reflective

        records: List[Mapping[str, Any]] = []
        trajectories = eval_batch.trajectories or []
        rng = random.Random(self.seed)

        for trajectory, output, score in zip(
            trajectories,
            eval_batch.outputs,
            eval_batch.scores,
        ):
            feedback = (
                "Correct: the selected action matched the final-level best WNS strategy."
                if score == 1.0
                else (
                    "Incorrect: select the action shown as expected_action, and revise the prompt "
                    "to improve routing decisions for this checkpoint state."
                )
            )
            records.append(
                {
                    "Inputs": {"checkpoint_state": trajectory["state"]},
                    "Generated Outputs": output,
                    "Feedback": feedback,
                }
            )

        rng.shuffle(records)
        reflective["routing_prompt"] = records[: min(12, len(records))]
        return reflective


def load_config(path: Path) -> Dict[str, Any]:
    if not path.exists():
        raise FileNotFoundError(f"Config file not found: {path}")
    with path.open("r", encoding="utf-8") as handle:
        config = json.load(handle)

    api_key = str(config.get("openrouter_api_key") or "").strip()
    if not api_key:
        import os
        api_key = os.environ.get("OPENROUTER_API_KEY", "").strip()
    if not api_key:
        raise ValueError("Set openrouter_api_key in gepa_config.json or OPENROUTER_API_KEY")

    config["openrouter_api_key"] = api_key
    return config


def load_dataset(path: Path) -> List[Dict[str, Any]]:
    if not path.exists():
        raise FileNotFoundError(f"Dataset not found: {path}")

    examples: List[Dict[str, Any]] = []
    with path.open("r", encoding="utf-8") as handle:
        for line_number, line in enumerate(handle, 1):
            if not line.strip():
                continue
            try:
                example = json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(f"Invalid JSON at {path}:{line_number}: {exc}") from exc

            required = ("best_wns_strategy_by_final_level",)
            if all(example.get(key) not in (None, "", "unknown") for key in required):
                examples.append(example)

    if not examples:
        raise ValueError("Dataset contains no usable examples")
    return examples


def sample_dataset(
    examples: Iterable[Dict[str, Any]],
    percentage: float,
    seed: int,
) -> List[Dict[str, Any]]:
    if not 0.0 < percentage <= 100.0:
        raise ValueError("dataset_percentage must be greater than 0 and at most 100")

    population = list(examples)
    count = max(1, int(round(len(population) * percentage / 100.0)))
    rng = random.Random(seed)
    indexes = list(range(len(population)))
    rng.shuffle(indexes)
    selected = [population[index] for index in indexes[:count]]
    return selected


def split_dataset(
    examples: Sequence[Dict[str, Any]],
    train_fraction: float,
) -> tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:
    if not 0.0 < train_fraction < 1.0:
        raise ValueError("train_fraction must be between 0 and 1")

    train_count = max(1, int(round(len(examples) * train_fraction)))
    if len(examples) == 1:
        train_count = 1
    train = list(examples[:train_count])
    val = list(examples[train_count:]) or list(train)
    return train, val


def main() -> None:
    config = load_config(CONFIG_PATH)

    dataset_path = Path(config.get("dataset_path", "gepa_training_output/gepa_examples.jsonl"))
    seed = int(config.get("seed", 42))
    percentage = float(config.get("dataset_percentage", 20.0))

    all_examples = load_dataset(dataset_path)
    selected = sample_dataset(all_examples, percentage, seed)
    trainset, valset = split_dataset(selected, float(config.get("train_fraction", 0.8)))

    task_lm = OpenRouterLM(
        api_key=config["openrouter_api_key"],
        model=str(config.get("task_model", "openrouter/openai/gpt-4.1-mini")),
        temperature=float(config.get("temperature", 0.2)),
        max_tokens=int(config.get("max_tokens", 300)),
        timeout_seconds=float(config.get("timeout_seconds", 120)),
    )
    reflection_lm = OpenRouterLM(
        api_key=config["openrouter_api_key"],
        model=str(config.get("reflection_model", "openrouter/openai/gpt-4.1")),
        temperature=float(config.get("reflection_temperature", 0.3)),
        max_tokens=int(config.get("reflection_max_tokens", 2000)),
        timeout_seconds=float(config.get("timeout_seconds", 120)),
    )

    adapter = FPGARoutingAdapter(task_lm=task_lm, seed=seed)

    litellm.drop_params = True
    litellm.set_verbose = False

    result = gepa.optimize(
        seed_candidate={"routing_prompt": BEGINNING_PROMPT},
        trainset=trainset,
        valset=valset,
        adapter=adapter,
        task_lm=task_lm,
        reflection_lm=reflection_lm,
        max_metric_calls=int(config.get("max_metric_calls", 100)),
        candidate_selection_strategy="pareto",
        skip_perfect_score=False,
        reflection_minibatch_size=min(12, len(trainset)),
        max_merge_invocations=0,
        seed=seed,
        run_dir=str(config.get("output_dir", "gepa_output")),
        display_progress_bar=True,
        raise_on_exception=True,
    )

    best_idx = int(result.best_idx)
    best_candidate = dict(result.candidates[best_idx])
    best_score = (
        float(result.val_aggregate_scores[best_idx])
        if result.val_aggregate_scores
        else 0.0
    )

    output_dir = Path(config.get("output_dir", "gepa_output"))
    output_dir.mkdir(parents=True, exist_ok=True)

    (output_dir / "optimized_routing_prompt.txt").write_text(
        best_candidate["routing_prompt"] + "\n",
        encoding="utf-8",
    )
    (output_dir / "optimized_routing_prompt.json").write_text(
        json.dumps(best_candidate, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )

    metadata = {
        "dataset_path": str(dataset_path),
        "full_dataset_examples": len(all_examples),
        "selected_dataset_examples": len(selected),
        "dataset_percentage": percentage,
        "train_examples": len(trainset),
        "val_examples": len(valset),
        "seed": seed,
        "task_model": str(config.get("task_model")),
        "reflection_model": str(config.get("reflection_model")),
        "max_metric_calls": int(config.get("max_metric_calls", 100)),
        "best_validation_score": best_score,
        "best_candidate_index": best_idx,
        "total_metric_calls": result.total_metric_calls,
    }
    (output_dir / "run_metadata.json").write_text(
        json.dumps(metadata, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )

    print(f"Selected {len(selected)} of {len(all_examples)} dataset examples ({percentage:g}%).")
    print(f"Train: {len(trainset)}, validation: {len(valset)}")
    print(f"Best validation score: {best_score:.4f}")
    print(f"Optimized prompt: {output_dir / 'optimized_routing_prompt.txt'}")


if __name__ == "__main__":
    main()
